#!/usr/bin/env node
// The doodle dingbats, split for pages: core.js and one file per family in
// public/s/db/, and db/names.mjs (name → family) so a page loads only the
// families it uses. Source: ../doodle-dingbats/src. Run after that set changes.
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url'; import { execFileSync } from 'node:child_process'
const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..')
const SRC = path.resolve(ROOT, '../doodle-dingbats/src')
const OUT = path.join(ROOT, 'public/s/db')
const esb = path.resolve(ROOT, '../anidoodle-motdang/node_modules/.bin/esbuild')
fs.mkdirSync(OUT, { recursive: true })
const min = (from, to) => execFileSync(esb, [from, '--minify', '--outfile=' + to, '--log-level=warning'])
min(path.join(SRC, 'core.js'), path.join(OUT, 'core.js'))
const names = {}
for (const f of fs.readdirSync(path.join(SRC, 'fam')).filter((f) => f.endsWith('.js')).sort()) {
  const fam = f.slice(0, -3)
  min(path.join(SRC, 'fam', f), path.join(OUT, fam + '.js'))
  for (const m of fs.readFileSync(path.join(SRC, 'fam', f), 'utf8').matchAll(/\badd\('([a-z0-9-]+)'/g)) names[m[1]] = fam
}
fs.writeFileSync(path.join(OUT, 'names.mjs'), '// generated by tools/dingbats.mjs — dingbat name → family file\nexport const DINGBATS = ' + JSON.stringify(names) + '\n')
const kb = (f) => (fs.statSync(path.join(OUT, f)).size / 1024).toFixed(0)
console.log(Object.keys(names).length, 'dingbats ·', fs.readdirSync(OUT).map((f) => f + ' ' + kb(f) + ' KB').join(' · '))
